def save_plan():
    global window

    if not hasattr(window, 'user_id'):
        messagebox.showerror("Authentication Error", "Please calculate your BMI first to register your profile.")
        return

    if not hasattr(window, 'current_plan_ids'):
        messagebox.showerror("Plan Error", "No diet plan was generated. Please ensure your inputs are valid.")
        return

    b_id, l_id, d_id = window.current_plan_ids

    if b_id == 0 or l_id == 0 or d_id == 0:
        messagebox.showerror("Selection Error", "The generated plan is incomplete. Cannot save.")
        return

    save_selection(window.user_id, b_id, l_id, d_id)
    messagebox.showinfo("Success",
                        "Your variety plan (based on the first option of each meal) has been saved! Enjoy your healthy meals!")


