def get_bmi_classification(bmi):
    if bmi < 18.5:
        return "Underweight", "Gain"
    elif bmi < 25.0:
        return "Normal weight", "Maintain"
    elif bmi < 30.0:
        return "Overweight", "Loss"
    else:
        return "Obese", "Loss"


def calculate_bmi(weight, height):
    height_m = height / 100
    bmi_value = round(weight / (height_m ** 2), 2)
    classification, goal = get_bmi_classification(bmi_value)
    return bmi_value, classification, goal


def calculate_target_weight(height, goal):
    height_m = height / 100
    if goal == "Gain":
        target_bmi = 20.0
    elif goal == "Loss":
        target_bmi = 23.0
    else:
        return None

    target_weight = round(target_bmi * (height_m ** 2), 1)
    return target_weight


def save_user(name, age, weight, height, bmi):
    conn = get_connection()
    if conn is None:
        return None
    cur = conn.cursor()

    try:
        cur.execute("SELECT user_id FROM users WHERE name = :p_name AND age = :p_age",
                    {"p_name": name, "p_age": age})
        row = cur.fetchone()

        if row:
            user_id = int(row[0])
            cur.execute("""
                UPDATE users SET weight_kg = :p_weight, height_cm = :p_height, bmi = :p_bmi
                WHERE user_id = :p_uid
            """, {
                "p_weight": weight, "p_height": height, "p_bmi": bmi, "p_uid": user_id
            })
        else:
            user_id_var = cur.var(oracledb.NUMBER)

            cur.execute("""
                -- **Insert 5 columns (excluding user_id):**
                INSERT INTO users (username, name, age, weight_kg, height_cm, bmi)
                -- **Provide 5 corresponding placeholders:**
                VALUES (:p_username, :p_name, :p_age, :p_weight, :p_height, :p_bmi)
                -- Use RETURNING INTO to capture the ID generated by the trigger.
                RETURNING user_id INTO :p_uid_out
            """, {
                "p_username": name,
                "p_name": name,
                "p_age": age,
                "p_weight": weight,
                "p_height": height,
                "p_bmi": bmi,
                "p_uid_out": user_id_var
            })

            user_id = int(user_id_var.getvalue()[0])

        conn.commit()
        return user_id

    except Exception as e:
        messagebox.showerror("Database Operation Error",
                             f"Error saving user data: {e}. Ensure the SQL setup file was run.")
        conn.rollback()
        return None
    finally:
        cur.close()


def load_all_options():
    global ALL_DIET_OPTIONS
    conn = get_connection()
    if conn is None:
        return {}
    cur = conn.cursor()

    options_by_type = {"breakfast": [], "lunch": [], "dinner": []}
    options_by_id = {}
    try:
        cur.execute("""
            SELECT option_id, meal_type, title, description, calories, protein_g, carbs_g, fats_g 
            FROM diet_options ORDER BY option_id
        """)
        rows = cur.fetchall()

        for row in rows:
            oid, meal_type, title, desc, cal, prot, carb, fat = row
            meal_data = {
                "oid": oid, "title": title, "description": desc, "calories": cal, "protein": prot, "carbs": carb,
                "fats": fat
            }
            options_by_id[oid] = meal_data
            if meal_type in options_by_type:
                options_by_type[meal_type].append(meal_data)

    except Exception as e:
        print(f"Error loading options: {e}")
        options_by_type = {}
    finally:
        cur.close()

    ALL_DIET_OPTIONS.update(options_by_id)
    return options_by_type


OPTIONS_BY_TYPE = load_all_options()


def get_filtered_options(goal):
    if goal == "Gain":
        b_filter = lambda m: 510 <= m['calories']
        l_filter = lambda m: 690 <= m['calories']
        d_filter = lambda m: 650 <= m['calories']
    elif goal == "Loss":
        b_filter = lambda m: 210 <= m['calories'] <= 250
        l_filter = lambda m: 230 <= m['calories'] <= 290
        d_filter = lambda m: 360 <= m['calories'] <= 420
    else:  # Maintain
        b_filter = lambda m: 350 <= m['calories'] <= 480
        l_filter = lambda m: 500 <= m['calories'] <= 540
        d_filter = lambda m: 400 <= m['calories'] <= 490

    breakfast_filtered = [m for m in OPTIONS_BY_TYPE.get("breakfast", []) if b_filter(m)][:3]
    lunch_filtered = [m for m in OPTIONS_BY_TYPE.get("lunch", []) if l_filter(m)][:3]
    dinner_filtered = [m for m in OPTIONS_BY_TYPE.get("dinner", []) if d_filter(m)][:3]

    return breakfast_filtered, lunch_filtered, dinner_filtered


def save_selection(uid, b_id, l_id, d_id):
    conn = get_connection()
    if conn is None:
        return
    cur = conn.cursor()

    plan_payload = {
        "breakfast_id": b_id,
        "lunch_id": l_id,
        "dinner_id": d_id
    }
    json_plan = json.dumps(plan_payload)

    try:
        selection_id_var = cur.var(oracledb.NUMBER)

        cur.execute("""
            INSERT INTO user_selections (user_id, full_plan_json)
            VALUES (:p_uid, :p_json)
            RETURNING selection_id INTO :p_sid_out
        """, {
            "p_uid": uid,
            "p_json": json_plan,
            "p_sid_out": selection_id_var
        })

        conn.commit()
    except Exception as e:
        messagebox.showerror("Database Operation Error",
                             f"Error saving selection: {e}. Ensure the SQL setup file was run.")
        conn.rollback()
    finally:
        cur.close()


def load_history(name, age):
    global ALL_DIET_OPTIONS
    conn = get_connection()
    if conn is None:
        return []
    cur = conn.cursor()

    history_list = []
    try:
        cur.execute("""
            SELECT u.age, u.bmi, s.full_plan_json, s.selection_time
            FROM user_selections s
            JOIN users u ON u.user_id = s.user_id
            WHERE u.name = :p_name AND u.age = :p_age
            ORDER BY s.selection_time DESC
        """, {"p_name": name, "p_age": age})
        rows = cur.fetchall()

        for row in rows:
            age_stored, bmi, json_data, time = row

            if hasattr(json_data, 'read'):
                json_data = json_data.read()

            try:
                plan_ids = json.loads(json_data)

                b_id = plan_ids.get("breakfast_id")
                l_id = plan_ids.get("lunch_id")
                d_id = plan_ids.get("dinner_id")

                b_obj = ALL_DIET_OPTIONS.get(b_id, {})
                b_title = b_obj.get("title", "N/A")
                b_desc = b_obj.get("description", "N/A")

                l_obj = ALL_DIET_OPTIONS.get(l_id, {})
                l_title = l_obj.get("title", "N/A")
                l_desc = l_obj.get("description", "N/A")

                d_obj = ALL_DIET_OPTIONS.get(d_id, {})
                d_title = d_obj.get("title", "N/A")
                d_desc = d_obj.get("description", "N/A")

                classification, _ = get_bmi_classification(bmi)

                history_list.append((
                    age_stored, bmi, classification,
                    b_title, b_desc,
                    l_title, l_desc,
                    d_title, d_desc,
                    time
                ))


            except Exception as json_e:
                print(f"Error parsing JSON for history entry: {json_e}")
                history_list.append((age_stored, bmi, 'N/A', 'Error', 'Error', 'Error', time))
                continue

        return history_list

    except Exception as e:
        messagebox.showerror("Database Load Error", f"Error loading history: {e}")
        return []
    finally:
        cur.close()


