def update_nutrition_display(b_id, l_id, d_id):
    total_calories = 0
    total_protein = 0
    total_carbs = 0
    total_fats = 0

    selected_ids = [b_id, l_id, d_id]

    for meal_id in selected_ids:
        if meal_id > 0 and meal_id in ALL_DIET_OPTIONS:
            meal = ALL_DIET_OPTIONS[meal_id]
            total_calories += meal['calories']
            total_protein += meal['protein']
            total_carbs += meal['carbs']
            total_fats += meal['fats']

    if 'label_total_cal' in globals() and label_total_cal.winfo_exists():
        label_total_cal.config(text=f"{total_calories} Kcal")
        label_total_prot.config(text=f"{total_protein} g")
        label_total_carb.config(text=f"{total_carbs} g")
        label_total_fat.config(text=f"{total_fats} g")


